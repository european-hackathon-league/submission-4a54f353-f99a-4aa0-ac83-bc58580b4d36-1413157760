def _norm(topic) -> str:
    return "None" if topic is None else str(topic).strip()


def write_review_files(topic_counts: Counter, study_attrs: list[str], force: bool = False) -> dict[str, int]:
    """Write car_areas.csv, vfc_topics.csv, study_attributes.csv, features.csv.

    Existing files hold the team's review and are never overwritten unless force=True.
    """
    REVIEW_DIR.mkdir(parents=True, exist_ok=True)
    if not force and (REVIEW_DIR / "features.csv").exists():
        return {"skipped": 1}
    with open(REVIEW_DIR / "car_areas.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["code", "name", "description", "confirmed"])
        for code, name, desc in CAR_AREAS:
            w.writerow([code, name, desc, ""])

    features: dict[str, dict] = {}
    unmapped = []
    with open(REVIEW_DIR / "vfc_topics.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["vfc_level2", "rows", "proposed_feature", "proposed_car_area", "proposed_by", "confirmed"])
        for topic, n in topic_counts.most_common():
            feature, area = VFC_TOPICS.get(topic, (None, None))
            if area is None:
                unmapped.append(topic)
                area = "general"
            w.writerow([topic, n, feature or "", area, PROPOSED_BY, ""])
            if feature:
                features.setdefault(feature, {"car_area": area, "vfc": 0, "study": 0})["vfc"] += n

    with open(REVIEW_DIR / "study_attributes.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["attribute", "proposed_feature", "proposed_by", "confirmed"])
        for attr in study_attrs:
            feature = STUDY_ATTRIBUTES.get(attr.strip())
            w.writerow([attr.strip(), feature or "", PROPOSED_BY, ""])
            if feature:
                if feature not in features:
                    raise ValueError(f"study attribute {attr!r} maps to unknown feature {feature!r}")
                features[feature]["study"] += 1

    with open(REVIEW_DIR / "features.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["feature", "car_area", "description", "vfc_rows", "study_attributes", "proposed_by", "confirmed"])
        for name, info in sorted(features.items(), key=lambda kv: (kv[1]["car_area"], kv[0])):
            w.writerow([name, info["car_area"], FEATURE_NOTES.get(name, ""), info["vfc"], info["study"],
                        PROPOSED_BY, ""])
    return {"car_areas": len(CAR_AREAS), "vfc_topics": len(topic_counts), "features": len(features),
            "unmapped_topics": len(unmapped), "study_attributes": len(study_attrs)}
