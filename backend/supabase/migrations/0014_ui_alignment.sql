-- PM region: one car line has a China PM and a rest-of-world PM.
-- CN = market China, RoW = every market except China, global = all markets.
create domain region_t as text
    check (value in ('global', 'RoW', 'CN'));

-- Readable ids for objects people quote (Q-0007, REF-0003): four digits, then the plain number.
create or replace function next_ref(prefix text, seq regclass) returns text
language sql set search_path = public, pg_temp as $$
    select prefix || case when n < 10000 then lpad(n::text, 4, '0') else n::text end
    from (select nextval(seq) as n) s
$$;

-- Drops the check constraints of a table whose definition mentions a marker
-- (the value sets below grow; constraint names were generated by Postgres).
create or replace function drop_checks_like(tbl regclass, marker text) returns void
language plpgsql set search_path = public, pg_temp as $$
declare
    c text;
begin
    for c in
        select conname from pg_constraint
        where conrelid = tbl and contype = 'c' and pg_get_constraintdef(oid) like '%' || marker || '%'
    loop
        execute format('alter table %s drop constraint %I', tbl, c);
    end loop;
end;
$$;

