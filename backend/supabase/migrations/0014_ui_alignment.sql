-- The lifecycle state stays observed / open / confirmed / rejected. While a case
-- is open the PM moves it through `workflow`; `outcome` is the PM's decision.
-- referred, innovation_pool and parked keep the case open for the line.
alter table case_vehicle
    add column owner_id     uuid references app_user (id),
    add column co_owner_ids uuid[] not null default '{}',
    add column watcher_ids  uuid[] not null default '{}',
    add column scope        region_t not null default 'global',
    add column workflow     text check (workflow in ('new', 'investigating', 'awaiting_answers', 'ready')),
    add column outcome      text check (outcome in (
                                'confirmed', 'referred', 'innovation_pool', 'parked', 'merged', 'rejected')),
    add column outcome_note text;

create or replace function case_vehicle_derive() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
    if new.state = 'observed' then
        new.workflow := null;
        new.outcome := null;
    elsif new.state = 'open' then
        new.workflow := coalesce(new.workflow, 'new');
        if new.outcome in ('confirmed', 'rejected', 'merged') then
            new.outcome := null;
        end if;
    elsif new.state = 'confirmed' then
        new.workflow := null;
        new.outcome := 'confirmed';
    else
        new.workflow := null;
        if new.outcome is null or new.outcome not in ('rejected', 'merged') then
            new.outcome := case when new.state_reason like 'merged into %' then 'merged' else 'rejected' end;
        end if;
    end if;
    return new;
end;
$$;
create trigger case_vehicle_derive before insert or update on case_vehicle
    for each row execute function case_vehicle_derive();
update case_vehicle set state = state;  -- existing rows get workflow and outcome
alter table case_vehicle add constraint case_vehicle_outcome_matches_state check (
    (state = 'observed' and workflow is null and outcome is null)
    or (state = 'open' and workflow is not null
        and (outcome is null or outcome in ('referred', 'innovation_pool', 'parked')))
    or (state = 'confirmed' and outcome = 'confirmed')
    or (state = 'rejected' and outcome in ('rejected', 'merged')));
create index case_vehicle_owner on case_vehicle (owner_id);

