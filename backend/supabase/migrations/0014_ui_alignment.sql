-- ---------------------------------------------------------------------------
-- 7. Security: same model as before (everything through the API)
-- ---------------------------------------------------------------------------

do $$
declare
    t text;
begin
    foreach t in array array[
        'workspace', 'series_brief', 'case_stance', 'requirement_version', 'requirement_feedback',
        'requirement_check', 'open_question', 'meeting_note', 'proposal', 'referral', 'innovation_item',
        'comment', 'alert', 'vehicle_plan', 'planned_feature']
    loop
        execute format('alter table public.%I enable row level security', t);
        if exists (select 1 from pg_roles where rolname = 'anon') then
            execute format('revoke all on public.%I from anon, authenticated', t);
        end if;
    end loop;
    if exists (select 1 from pg_roles where rolname = 'anon') then
        execute 'revoke all on public.requirement_check_current from anon, authenticated';
    end if;
    -- Realtime: a person reads the broadcasts and their own inbox items only.
    if exists (select 1 from pg_roles where rolname = 'authenticated')
       and to_regprocedure('auth.uid()') is not null then
        execute 'drop policy if exists notification_read on public.notification';
        execute 'create policy notification_read on public.notification for select to authenticated'
                ' using (user_id is null or user_id = auth.uid())';
    end if;
end;
$$;
